"""Multi-provider async LLM router with a zero-key fallback chain.

Each request walks an ordered chain of engines and falls through on any failure; the engine label records the route
("codex_cli", "chatgpt_browser->codex_cli", "claude_cli->deterministic"). Chains (docs/specs/chatgpt-engine FR2):

  auto              API keys (Anthropic → OpenAI → Gemini → OpenRouter) → claude CLI → Codex CLI
  <key provider>    that provider (when its key is set) → claude CLI → Codex CLI
  claude_cli        claude CLI → Codex CLI
  codex_cli         Codex CLI → claude CLI
  chatgpt_browser   ChatGPT browser (private local engine) → Codex CLI → claude CLI

and finally the deterministic engine (callers treat a `None` result as "use the deterministic SymPy/graph content").
"Automatic" never picks the browser engine.

A failing local engine (missing, logged out, nested-session lock, timeout, usage limit) trips a 10-minute circuit
breaker so a broken engine never stalls every step for the full timeout; an engine that needs the user (login or
"verify you are human" page) trips a 2-minute one and asks for attention over the WebSocket.

Optional local engines: `backend/local_engines/__init__.py` (git-ignored, absent from the public repo) may expose
`ENGINES: dict[str, Engine]`, where an Engine has `available() -> bool`, `async complete(system, user) -> str` and
`status() -> dict`. It may raise `NeedsUser(reason)` from this module.
"""
from __future__ import annotations

import asyncio
import contextvars
import json
import os
import re
import subprocess
import tempfile
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Optional

import httpx

from . import config
from .config import settings

CLI_COOLDOWN_S = 600.0
ATTENTION_COOLDOWN_S = 120.0
KEY_PROVIDERS = ("anthropic", "openai", "gemini", "openrouter")
_disabled_until: dict[str, float] = {}
_last_error: dict[str, str] = {}
# Set inside seeding so the seed dataset is generated by the deterministic engine without network calls.
force_deterministic: contextvars.ContextVar[bool] = contextvars.ContextVar("force_deterministic", default=False)

LOCAL_ENGINES: dict[str, Any] = {}   # filled at the end of this module (private engines import from it)


class NeedsUser(RuntimeError):
    """The engine is blocked on something only the user can do (sign in, a challenge page, a usage limit)."""


@dataclass
class LLMResult:
    data: Optional[dict[str, Any]]
    engine: str
    raw: str = ""
    error: str = ""


def keys_present() -> dict[str, bool]:
    return {k: bool(v) for k, v in settings.keys.items()}


def _cooling(name: str) -> bool:
    return time.monotonic() < _disabled_until.get(name, 0.0)


def _trip(name: str, error: str, cooldown: float = CLI_COOLDOWN_S) -> None:
    _disabled_until[name] = time.monotonic() + cooldown
    _last_error[name] = error[-400:]


def claude_cli_available() -> bool:
    return bool(settings.claude_cli_path()) and not _cooling("claude_cli")


_codex_login: tuple[float, bool] = (0.0, False)


def codex_installed() -> bool:
    """Codex is on this Mac and signed in (`codex login status`, cached for a minute). Tokens are never read."""
    global _codex_login
    exe = settings.codex_cli_path()
    if not exe:
        return False
    checked, ok = _codex_login
    if time.monotonic() - checked > 60:
        try:
            ok = subprocess.run([exe, "login", "status"], capture_output=True, timeout=10, stdin=subprocess.DEVNULL).returncode == 0
        except (OSError, subprocess.SubprocessError):
            ok = False
        _codex_login = (time.monotonic(), ok)
    return ok


def codex_available() -> bool:
    return not _cooling("codex_cli") and codex_installed()


def local_engine(name: str) -> Any:
    return LOCAL_ENGINES.get(name)


def _local_available(name: str) -> bool:
    eng = local_engine(name)
    if not eng or _cooling(name):
        return False
    try:
        return bool(eng.available())
    except Exception:
        return False


def engine_chain() -> list[str]:
    """Ordered engines to try for the next request (without the final deterministic fallback)."""
    p = settings.provider
    if force_deterministic.get() or config.env("LLM") == "deterministic" or p == "deterministic":
        return []
    keyed = [k for k in KEY_PROVIDERS if settings.keys.get(k)]
    if p == "auto":
        order = keyed + ["claude_cli", "codex_cli"]
    elif p in KEY_PROVIDERS:
        order = ([p] if settings.keys.get(p) else []) + ["claude_cli", "codex_cli"]
    elif p == "codex_cli":
        order = ["codex_cli", "claude_cli"]
    elif p == "chatgpt_browser":
        order = ["chatgpt_browser", "codex_cli", "claude_cli"]
    else:
        order = ["claude_cli", "codex_cli"]
    avail = {"claude_cli": claude_cli_available, "codex_cli": codex_available}
    out = []
    for name in order:
        if name in KEY_PROVIDERS or (name in avail and avail[name]()) or (name in LOCAL_ENGINES and _local_available(name)):
            out.append(name)
    return out


def resolve_engine() -> str:
    chain = engine_chain()
    return chain[0] if chain else "deterministic"


def describe_engine() -> str:
    e = resolve_engine()
    if e in settings.models:
        return f"{e}:{settings.models[e]}"
    return e


def engine_status() -> dict[str, Any]:
    """What Settings shows about the local engines."""
    out: dict[str, Any] = {"codex_available": codex_installed(), "codex_last_error": _last_error.get("codex_cli")}
    eng = local_engine("chatgpt_browser")
    if eng:
        try:
            st = dict(eng.status())
        except Exception as e:
            st = {"signed_in": None, "last_error": str(e)[:200]}
        st["available"] = True
        st["last_error"] = st.get("last_error") or _last_error.get("chatgpt_browser")
        out["chatgpt_browser"] = st
    else:
        out["chatgpt_browser"] = {"available": False, "signed_in": None, "last_error": None}
    return out


def extract_json(text: str) -> Optional[dict[str, Any]]:
    """Pull the first JSON object out of model text (handles ```json fences and prose wrappers)."""
    if not text:
        return None
    fence = re.search(r"```(?:json)?\s*(\{.*?\})\s*```", text, re.S)
    candidates = [fence.group(1)] if fence else []
    start = text.find("{")
    if start >= 0:
        depth = 0
        in_str = esc = False
        for i in range(start, len(text)):
            ch = text[i]
            if in_str:
                if esc:
                    esc = False
                elif ch == "\\":
                    esc = True
                elif ch == '"':
                    in_str = False
                continue
            if ch == '"':
                in_str = True
            elif ch == "{":
                depth += 1
            elif ch == "}":
                depth -= 1
                if depth == 0:
                    candidates.append(text[start:i + 1])
                    break
    for c in candidates:
        try:
            obj = json.loads(c)
            if isinstance(obj, dict):
                return obj
        except json.JSONDecodeError:
            continue
    return None


JSON_RULE = ("\n\nRespond with ONE JSON object only — no prose before or after, no markdown fences. "
             "Use KaTeX-compatible LaTeX inside strings ($...$ inline, $$...$$ display) with backslashes escaped for JSON.")


async def _anthropic(system: str, user: str, max_tokens: int) -> str:
    async with httpx.AsyncClient(timeout=60) as c:
        r = await c.post("https://api.anthropic.com/v1/messages", headers={
            "x-api-key": settings.keys["anthropic"], "anthropic-version": "2023-06-01", "content-type": "application/json",
        }, json={"model": settings.models["anthropic"], "max_tokens": max_tokens, "system": system,
                 "messages": [{"role": "user", "content": user}]})
        r.raise_for_status()
        return "".join(b.get("text", "") for b in r.json().get("content", []) if b.get("type") == "text")


async def _openai_compatible(url: str, key: str, model: str, system: str, user: str, max_tokens: int) -> str:
    async with httpx.AsyncClient(timeout=60) as c:
        r = await c.post(url, headers={"Authorization": f"Bearer {key}", "content-type": "application/json"}, json={
            "model": model, "max_tokens": max_tokens, "response_format": {"type": "json_object"},
            "messages": [{"role": "system", "content": system}, {"role": "user", "content": user}],
        })
        r.raise_for_status()
        return r.json()["choices"][0]["message"]["content"]


async def _gemini(system: str, user: str, max_tokens: int) -> str:
    model = settings.models["gemini"]
    url = f"https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent"
    async with httpx.AsyncClient(timeout=60) as c:
        r = await c.post(url, params={"key": settings.keys["gemini"]}, json={
            "systemInstruction": {"parts": [{"text": system}]},
            "contents": [{"role": "user", "parts": [{"text": user}]}],
            "generationConfig": {"responseMimeType": "application/json", "maxOutputTokens": max_tokens},
        })
        r.raise_for_status()
        parts = r.json()["candidates"][0]["content"]["parts"]
        return "".join(p.get("text", "") for p in parts)


async def _claude_cli(system: str, user: str) -> str:
    exe = settings.claude_cli_path()
    if not exe:
        raise RuntimeError("claude CLI not on PATH")
    env = {k: v for k, v in os.environ.items() if not k.startswith("CLAUDE_CODE") and k not in ("CLAUDECODE",)}
    prompt = f"<system>\n{system}\n</system>\n\n{user}"
    proc = await asyncio.create_subprocess_exec(
        exe, "-p", "--output-format", "json", stdin=asyncio.subprocess.PIPE,
        stdout=asyncio.subprocess.PIPE, stderr=asyncio.subprocess.PIPE, env=env, cwd=str(config.WORKSPACE),
    )
    try:
        out, err = await asyncio.wait_for(proc.communicate(prompt.encode()), timeout=config.CLAUDE_CLI_TIMEOUT_S)
    except asyncio.TimeoutError:
        proc.kill()
        _trip("claude_cli", "timeout")
        raise RuntimeError("claude CLI timed out")
    if proc.returncode != 0:
        _trip("claude_cli", err.decode(errors="replace") or out.decode(errors="replace"))
        raise RuntimeError(f"claude CLI failed: {_last_error['claude_cli']}")
    envelope = json.loads(out.decode(errors="replace"))
    if envelope.get("is_error"):
        _trip("claude_cli", str(envelope.get("result", "")))
        raise RuntimeError(f"claude CLI error: {_last_error['claude_cli']}")
    return envelope.get("result", "")


async def _codex_cli(system: str, user: str) -> str:
    """`codex exec` signed in with the user's ChatGPT plan. Ephemeral, read-only sandbox in an empty temp dir, the
    user's Codex config/hooks/rules ignored, prompt on stdin, final message read from -o (chatgpt-engine FR1)."""
    exe = settings.codex_cli_path()
    if not exe:
        raise RuntimeError("codex CLI not on PATH")
    prompt = f"<system>\n{system}\n</system>\n\n{user}\n\nDo not run commands or edit files; just reply."
    with tempfile.TemporaryDirectory(prefix="polya-codex-") as d:
        last = Path(d) / "last.txt"
        args = [exe, "exec", "--ephemeral", "--skip-git-repo-check", "--ignore-user-config", "--ignore-rules",
                "-s", "read-only", "--color", "never", "-C", d, "-o", str(last)]
        if config.env("CODEX_MODEL"):
            args += ["-m", config.env("CODEX_MODEL")]
        proc = await asyncio.create_subprocess_exec(*args, "-", stdin=asyncio.subprocess.PIPE,
                                                    stdout=asyncio.subprocess.PIPE, stderr=asyncio.subprocess.PIPE, cwd=d)
        try:
            out, err = await asyncio.wait_for(proc.communicate(prompt.encode()), timeout=config.CODEX_TIMEOUT_S)
        except asyncio.TimeoutError:
            proc.kill()
            _trip("codex_cli", "timeout")
            raise RuntimeError("codex CLI timed out")
        text = last.read_text(errors="replace") if last.exists() else ""
        if proc.returncode != 0 or not text.strip():
            _trip("codex_cli", err.decode(errors="replace") or out.decode(errors="replace") or "empty reply")
            raise RuntimeError(f"codex CLI failed: {_last_error['codex_cli']}")
        return text


async def _local(name: str, system: str, user: str) -> str:
    from .hub import hub
    try:
        return await local_engine(name).complete(system, user)
    except NeedsUser as e:
        _trip(name, str(e), ATTENTION_COOLDOWN_S)
        await hub.broadcast("engine_attention", {"engine": name, "reason": str(e)})
        raise
    except Exception as e:
        _trip(name, str(e) or type(e).__name__)
        raise


async def _call(engine: str, system: str, user: str, max_tokens: int) -> str:
    if engine == "anthropic":
        return await _anthropic(system, user, max_tokens)
    if engine == "openai":
        return await _openai_compatible("https://api.openai.com/v1/chat/completions", settings.keys["openai"],
                                        settings.models["openai"], system, user, max_tokens)
    if engine == "openrouter":
        return await _openai_compatible("https://openrouter.ai/api/v1/chat/completions", settings.keys["openrouter"],
                                        settings.models["openrouter"], system, user, max_tokens)
    if engine == "gemini":
        return await _gemini(system, user, max_tokens)
    if engine == "codex_cli":
        return await _codex_cli(system, user)
    if engine in LOCAL_ENGINES:
        return await _local(engine, system, user)
    return await _claude_cli(system, user)


async def complete_json(system: str, user: str, max_tokens: int = 2500) -> LLMResult:
    """Ask the engine chain for a JSON object. `data is None` means: use deterministic content."""
    chain = engine_chain()
    if not chain:
        return LLMResult(None, "deterministic")
    system = system + JSON_RULE
    tried: list[str] = []
    errors: list[str] = []
    raw = ""
    for engine in chain:
        tried.append(engine)
        try:
            raw = await _call(engine, system, user, max_tokens)
        except Exception as e:  # network, auth, CLI lock, limit, page change: try the next engine
            errors.append(f"{engine}: {str(e)[:300]}")
            continue
        data = extract_json(raw)
        if data is not None:
            return LLMResult(data, "->".join(tried), raw=raw[:4000])
        errors.append(f"{engine}: no JSON object in response")
    return LLMResult(None, "->".join(tried + ["deterministic"]), raw=raw[:2000], error=" | ".join(errors)[-800:])


